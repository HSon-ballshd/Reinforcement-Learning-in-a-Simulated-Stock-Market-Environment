"""
Regime classifier — LogReg, RandomForest, MLP.

Trained on data/regime_dataset.parquet (generated by Sim).
Hypothesis H2: classifier beats random guessing (1/6 ≈ 16.7%).
"""

from __future__ import annotations

import pickle
import numpy as np
import pandas as pd
from pathlib import Path
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, classification_report

# Regime labels (match minigameMarket.js modes)
REGIME_NAMES = {
    0: 'Stable',
    1: 'Bullish',
    2: 'Bearish',
    3: 'Strong Bull',
    4: 'Strong Bear',
    5: 'Chaotic',
}
N_CLASSES = len(REGIME_NAMES)


class RegimeClassifierPipeline:
    """
    End-to-end pipeline: load data → scale → train → evaluate.

    Three models are trained and the best one (by val accuracy) is kept
    as `self.best_model`.  All models are serialised to `out_dir`.
    """

    FEATURE_COLS = [
        'return_1', 'return_5', 'return_20',
        'rolling_mean_5', 'rolling_mean_20', 'rolling_std_20',
        'momentum_5_20',
    ]
    # 'price' is excluded — it scales with bank_level and stock_id, not regime.

    def __init__(
        self,
        data_path: str | Path = "data/regime_dataset.parquet",
        out_dir: str | Path = "models",
        test_size: float = 0.2,
        random_state: int = 42,
    ) -> None:
        self.data_path    = Path(data_path)
        self.out_dir     = Path(out_dir)
        self.test_size   = test_size
        self.random_state = random_state

        self.scaler: StandardScaler | None       = None
        self.models: dict[str, object]            = {}
        self.scores:  dict[str, float]            = {}
        self.best_name: str                        = ''
        self.best_model: object | None             = None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def run(self) -> dict[str, float]:
        """
        Run the full pipeline: load → split → scale → train → evaluate.

        Returns a dict mapping model name → test accuracy.
        """
        df = self._load_data()
        X_train, X_test, y_train, y_test = self._split(df)
        X_train, X_test = self._scale(X_train, X_test)

        for name, model in self._model_factory().items():
            model.fit(X_train, y_train)
            preds   = model.predict(X_test)
            acc     = accuracy_score(y_test, preds)
            self.models[name] = model
            self.scores[name] = acc
            print(f"{name}: accuracy = {acc:.4f}")

        # Select best model
        self.best_name  = max(self.scores, key=self.scores.get)
        self.best_model = self.models[self.best_name]
        print(f"\nBest model: {self.best_name} ({self.scores[self.best_name]:.4f})")

        self._save()
        self._report_detail(X_test, y_test)

        return self.scores

    def predict(self, observation: np.ndarray) -> int:
        """
        Classify a single market observation.

        Args:
            observation: array-like of shape (7,) — the 7 non-price features
                        in the same order as FEATURE_COLS.

        Returns:
            Predicted regime (0–5).
        """
        if self.scaler is None or self.best_model is None:
            raise RuntimeError("Pipeline not run yet — call run() first.")
        x = np.asarray(observation, dtype=np.float32).reshape(1, -1)
        x = self.scaler.transform(x)
        return int(self.best_model.predict(x)[0])

    # ------------------------------------------------------------------
    # Internal steps
    # ------------------------------------------------------------------
    def _load_data(self) -> pd.DataFrame:
        if not self.data_path.exists():
            raise FileNotFoundError(
                f"Dataset not found at {self.data_path}. "
                "Run sim.market_sim.dataset.generate_regime_dataset() first."
            )
        df = pd.read_parquet(self.data_path)

        # Drop rows with NaN (early ticks don't have enough history for
        # return_5 / return_20 / rolling_*)
        before = len(df)
        df = df.dropna()
        dropped = before - len(df)
        if dropped:
            print(f"Dropped {dropped}/{before} rows with NaN features.")

        return df

    def _split(self, df: pd.DataFrame):
        X = df[self.FEATURE_COLS].values
        y = df['mode'].values

        return train_test_split(
            X, y,
            test_size=self.test_size,
            random_state=self.random_state,
            stratify=y,
        )

    def _scale(self, X_train, X_test):
        self.scaler = StandardScaler()
        X_train = self.scaler.fit_transform(X_train)
        X_test  = self.scaler.transform(X_test)
        return X_train, X_test

    def _model_factory(self) -> dict:
        return {
            "LogReg": LogisticRegression(
                max_iter=1000,
                solver='lbfgs',
                random_state=self.random_state,
            ),
            "RandomForest": RandomForestClassifier(
                n_estimators=200,
                max_depth=15,
                min_samples_leaf=5,
                random_state=self.random_state,
                n_jobs=-1,
            ),
            "MLP": MLPClassifier(
                hidden_layer_sizes=(128, 64),
                activation='relu',
                max_iter=500,
                early_stopping=True,
                validation_fraction=0.1,
                random_state=self.random_state,
            ),
        }

    def _save(self) -> None:
        self.out_dir.mkdir(parents=True, exist_ok=True)
        pickle.dump(self.scaler,       open(self.out_dir / "scaler.pkl",      "wb"))
        pickle.dump(self.best_model,    open(self.out_dir / "best_model.pkl",   "wb"))
        pickle.dump(self.models,        open(self.out_dir / "all_models.pkl",   "wb"))
        print(f"\nSaved models to {self.out_dir}/")

    def _report_detail(self, X_test, y_test) -> None:
        preds = self.best_model.predict(X_test)
        print(f"\nClassification report for {self.best_name}:")
        print(classification_report(
            y_test, preds,
            target_names=[REGIME_NAMES[i] for i in range(N_CLASSES)],
        ))


# ------------------------------------------------------------------
# CLI entry point
# ------------------------------------------------------------------
if __name__ == "__main__":
    import sys

    data_path = Path(sys.argv[1]) if len(sys.argv) > 1 else "data/regime_dataset.parquet"
    out_dir   = Path(sys.argv[2]) if len(sys.argv) > 2 else "models"

    pipeline = RegimeClassifierPipeline(data_path=data_path, out_dir=out_dir)
    scores = pipeline.run()

    # Baseline: random guessing
    baseline = 1.0 / N_CLASSES
    print(f"\nBaseline (random): {baseline:.4f}")
    for name, acc in scores.items():
        delta = acc - baseline
        print(f"  {name}: {delta:+.4f} vs random")
