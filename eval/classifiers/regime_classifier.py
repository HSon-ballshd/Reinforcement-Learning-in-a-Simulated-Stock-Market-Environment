"""
Regime classifier — LogReg, RandomForest, MLP.

Trained on data/regime_dataset.parquet (generated by Sim).
Hypothesis H2: classifier beats random guessing (1/6 ≈ 16.7%).
"""

from __future__ import annotations

import pickle
import numpy as np
import pandas as pd
from pathlib import Path
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import (
    RandomForestClassifier,
    ExtraTreesClassifier,
    GradientBoostingClassifier,
)
from sklearn.neural_network import MLPClassifier
from sklearn.calibration import CalibratedClassifierCV
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, classification_report

# Regime labels (match minigameMarket.js modes)
REGIME_NAMES = {
    0: 'Stable',
    1: 'Bullish',
    2: 'Bearish',
    3: 'Strong Bull',
    4: 'Strong Bear',
    5: 'Chaotic',
}
N_CLASSES = len(REGIME_NAMES)


class RegimeClassifierPipeline:
    """
    End-to-end pipeline: load data → split → scale → train → evaluate.

    Uses a three-way split to avoid selection bias:
        60% train  — fit the scaler and train models
        20% val    — select the best model (no leakage)
        20% test   — report final accuracy on held-out data

    Three models are trained and the best one (by val accuracy) is kept
    as `self.best_model`.  All models are serialised to `out_dir`.
    """

    FEATURE_COLS = [
        # === Returns at multiple timescales ===
        'return_1', 'return_5', 'return_10', 'return_20',
        # === Volatility and mean-reversion ===
        'rolling_std_5', 'rolling_std_20', 'rolling_std_ratio',
        'mean_reversion_z',      # (price - rolling_mean_20) / rolling_std_20
        # === Drift / directional pressure ===
        'directional_consistency_5',  # % up-ticks in last 5
        'directional_consistency_20', # % up-ticks in last 20
        'drift_estimate_5',     # sign-weighted mean return over 5 ticks
        # === Jump detection (key for Strong Bull/Bear) ===
        'jump_count_5',         # number of |tick_return| > 1 std_5 in last 5
        'jump_count_20',        # number of |tick_return| > 1 std_20 in last 20
        'max_tick_return_5',   # max |tick_return| in last 5 — Strong modes have large jumps
        # === Trend strength ===
        'trend_strength_5',     # return_5 / rolling_std_5 — trending vs noisy
        'trend_strength_20',    # return_20 / rolling_std_20
        # === Momentum divergence (Chaotic flips direction) ===
        'momentum_divergence',  # 1 if return_1 and return_20 disagree in sign
        # === Volatility regime ===
        'vol_regime_5',        # std_5 / rolling_std_20 — high = volatile/Chaotic
    ]
    # 'price' is excluded — it scales with bank_level and stock_id, not regime.

    def __init__(
        self,
        data_path: str | Path = "data/regime_dataset.parquet",
        out_dir: str | Path = "models",
        train_size: float = 0.6,
        val_size: float = 0.2,
        test_size: float = 0.2,
        random_state: int = 42,
    ) -> None:
        self.data_path    = Path(data_path)
        self.out_dir     = Path(out_dir)
        self.train_size  = train_size
        self.val_size    = val_size
        self.test_size   = test_size
        self.random_state = random_state

        self.scaler: StandardScaler | None     = None
        self.models: dict[str, object]          = {}
        self.val_scores: dict[str, float]      = {}
        self.test_scores: dict[str, float]     = {}
        self.best_name: str                    = ''
        self.best_model: object | None         = None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def run(self) -> dict:
        """
        Run the full three-way pipeline.

        Returns a dict with:
            - val_scores  (used for model selection)
            - test_scores (final held-out accuracy)
            - best_name   (which model was selected)
        """
        df = self._load_data()
        X_train_val, X_test, y_train_val, y_test = self._split(df, self.train_size + self.val_size)
        X_train, X_val, y_train, y_val = self._split(
            (X_train_val, y_train_val), self.train_size / (self.train_size + self.val_size)
        )

        # Scale: fit on train only, apply to val and test
        X_train, X_val, X_test = self._scale(X_train, X_val, X_test)

        # Train all models on train split
        for name, model in self._model_factory().items():
            model.fit(X_train, y_train)
            # Validate on val split (no leakage into model selection)
            val_preds = model.predict(X_val)
            val_acc   = accuracy_score(y_val, val_preds)
            self.models[name] = model
            self.val_scores[name] = val_acc
            print(f"  {name}: val_acc = {val_acc:.4f}")

        # Stacking ensemble: use base-model OOF probability predictions as meta-features
        from sklearn.ensemble import StackingClassifier
        stacking = StackingClassifier(
            estimators=list(self._model_factory().items()),
            final_estimator=LogisticRegression(max_iter=2000, C=1.0, random_state=self.random_state),
            cv=5,   # 5-fold internal CV to generate meta-features for the meta-learner
            passthrough=False,   # only use base model probabilities, not original features
            n_jobs=-1,
        )
        stacking.fit(X_train, y_train)
        stack_val_preds = stacking.predict(X_val)
        stack_val_acc  = accuracy_score(y_val, stack_val_preds)
        self.models["Stacking"] = stacking
        self.val_scores["Stacking"] = stack_val_acc
        print(f"  Stacking:  val_acc = {stack_val_acc:.4f}")

        # Select best model by val accuracy
        self.best_name  = max(self.val_scores, key=self.val_scores.get)
        self.best_model = self.models[self.best_name]
        print(f"\n  Best (by val): {self.best_name} ({self.val_scores[self.best_name]:.4f})")

        # Report test accuracy ONLY for the selected best model
        test_preds = self.best_model.predict(X_test)
        test_acc   = accuracy_score(y_test, test_preds)
        self.test_scores[self.best_name] = test_acc
        print(f"  Test accuracy ({self.best_name}): {test_acc:.4f}")

        # Report test accuracy for all models (transparency)
        print(f"\n  All models — test accuracy:")
        for name, model in self.models.items():
            tp = model.predict(X_test)
            ta = accuracy_score(y_test, tp)
            self.test_scores[name] = ta
            mark = " ← SELECTED" if name == self.best_name else ""
            print(f"    {name}: {ta:.4f}{mark}")

        self._save()
        self._report_detail(X_test, y_test, self.best_name)

        return {
            "val_scores":  self.val_scores,
            "test_scores": self.test_scores,
            "best_name":   self.best_name,
        }

    def predict(self, observation: np.ndarray) -> int:
        """
        Classify a single market observation.

        Args:
            observation: array-like of shape (18,) matching FEATURE_COLS order.

        Returns:
            Predicted regime (0–5).
        """
        if self.scaler is None or self.best_model is None:
            raise RuntimeError("Pipeline not run yet — call run() first.")
        x = np.asarray(observation, dtype=np.float32).reshape(1, -1)
        x = self.scaler.transform(x)
        return int(self.best_model.predict(x)[0])

    # ------------------------------------------------------------------
    # Internal steps
    # ------------------------------------------------------------------
    def _load_data(self) -> pd.DataFrame:
        if not self.data_path.exists():
            raise FileNotFoundError(
                f"Dataset not found at {self.data_path}. "
                "Run sim.market_sim.dataset.generate_regime_dataset() first."
            )
        df = pd.read_parquet(self.data_path)

        # Drop rows with NaN (early ticks don't have enough history for
        # return_5 / return_20 / rolling_*)
        before = len(df)
        df = df.dropna()
        dropped = before - len(df)
        if dropped:
            print(f"Dropped {dropped}/{before} rows with NaN features.")

        return df

    def _split(self, Xy, test_size: float):
        """
        Split data into two parts.

        Accepts either:
            - a DataFrame (first call) → extracts features/labels and splits
            - a tuple (X, y)         → splits both arrays directly
        """
        if isinstance(Xy, pd.DataFrame):
            X = Xy[self.FEATURE_COLS].values
            y = Xy['mode'].values
        else:
            X, y = Xy

        return train_test_split(
            X, y,
            test_size=test_size,
            random_state=self.random_state,
            stratify=y,
        )

    def _scale(self, X_train, X_val, X_test):
        """
        Fit scaler on train only; transform val and test with it.
        This prevents leakage — test data never influences normalisation.
        """
        self.scaler = StandardScaler()
        X_train = self.scaler.fit_transform(X_train)
        X_val   = self.scaler.transform(X_val)
        X_test  = self.scaler.transform(X_test)
        return X_train, X_val, X_test

    def _model_factory(self) -> dict:
        return {
            "LogReg": LogisticRegression(
                max_iter=2000,
                solver='lbfgs',
                C=0.5,
                random_state=self.random_state,
            ),
            "RandomForest": RandomForestClassifier(
                n_estimators=500,
                max_depth=None,       # let trees grow fully
                min_samples_leaf=2,
                min_samples_split=4,
                random_state=self.random_state,
                n_jobs=-1,
            ),
            "ExtraTrees": ExtraTreesClassifier(
                n_estimators=500,
                max_depth=None,
                min_samples_leaf=2,
                random_state=self.random_state,
                n_jobs=-1,
            ),
            "GradBoost": GradientBoostingClassifier(
                n_estimators=300,
                max_depth=6,
                learning_rate=0.05,
                subsample=0.8,
                random_state=self.random_state,
            ),
            "MLP": MLPClassifier(
                hidden_layer_sizes=(256, 128, 64),
                activation='relu',
                max_iter=1000,
                early_stopping=True,
                validation_fraction=0.1,
                random_state=self.random_state,
            ),
        }

    def _save(self) -> None:
        self.out_dir.mkdir(parents=True, exist_ok=True)
        pickle.dump(self.scaler,       open(self.out_dir / "scaler.pkl",      "wb"))
        pickle.dump(self.best_model,    open(self.out_dir / "best_model.pkl",   "wb"))
        pickle.dump(self.models,        open(self.out_dir / "all_models.pkl",   "wb"))
        print(f"\nSaved models to {self.out_dir}/")

    def _report_detail(self, X_test, y_test, model_name: str | None = None) -> None:
        model = self.models[model_name or self.best_name]
        preds = model.predict(X_test)
        name  = model_name or self.best_name
        print(f"\nClassification report for {name}:")
        print(classification_report(
            y_test, preds,
            target_names=[REGIME_NAMES[i] for i in range(N_CLASSES)],
        ))


# ------------------------------------------------------------------
# CLI entry point
# ------------------------------------------------------------------
if __name__ == "__main__":
    import sys

    data_path = Path(sys.argv[1]) if len(sys.argv) > 1 else "data/regime_dataset.parquet"
    out_dir   = Path(sys.argv[2]) if len(sys.argv) > 2 else "models"

    pipeline = RegimeClassifierPipeline(data_path=data_path, out_dir=out_dir)
    result = pipeline.run()

    # val_scores: used for model selection (reported transparently)
    baseline = 1.0 / N_CLASSES
    print(f"\n--- Val Accuracy (model selection) ---")
    print(f"Baseline (random): {baseline:.4f}")
    for name, acc in result["val_scores"].items():
        mark = " ← SELECTED" if name == result["best_name"] else ""
        print(f"  {name}: {acc:.4f}  (Δ {acc - baseline:+.4f}){mark}")

    # test_scores: held-out accuracy (final reported number)
    print(f"\n--- Test Accuracy (held-out, final) ---")
    for name, acc in result["test_scores"].items():
        mark = " ← SELECTED" if name == result["best_name"] else ""
        print(f"  {name}: {acc:.4f}  (Δ {acc - baseline:+.4f}){mark}")
